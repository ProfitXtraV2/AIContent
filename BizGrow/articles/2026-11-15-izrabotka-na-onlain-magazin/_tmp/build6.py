  'status = "draft"', 'last_updated = "2026-11-15"',
  f'path = "/{SLUG}/"', f"eyebrow = {tq(eyebrow)}", f"label = {tq(label)}",
  f"summary = {tq(summary)}", f"lead = {tq(lead)}", f"service = {tq(service)}",
