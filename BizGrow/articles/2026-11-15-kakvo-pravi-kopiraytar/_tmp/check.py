import tomllib, json, re
W="content/"
md=open(W+"kakvo-pravi-kopiraytar.md",encoding="utf-8").read()
fm=md.split("+++")[1]; body=md.split("+++",2)[2]
d=tomllib.loads(fm); p=json.load(open(W+"kakvo-pravi-kopiraytar.port.json",encoding="utf-8"))
R=[]
def c(n,ok,info=""): R.append((n,"PASS" if ok else "FAIL",info))
c("TOML parses",True)
c("title<=60",len(d["title"])<=60,len(d["title"]))
c("meta 120-160",120<=len(d["meta_description"])<=160,len(d["meta_description"]))
c("meta has term","копирайтър" in d["meta_description"])
c("summary<=160",len(p["summary"])<=160,len(p["summary"]))
c("primary kw","копирайтър"==d["primary_keyword"]==p["primaryKeyword"])
first100=" ".join(re.findall(r"\S+",p["lead"])[:100])
c("term in first 100 words","копирайтър" in first100.lower())
c("term in title","копирайтър" in d["title"].lower())
c("term in H1 (variant)","копирайтър" in d["h1"].lower(), d["h1"])
c("term in an H2",sum("копирайтър" in s["title"].lower() for s in p["sections"])>=1)
heads=re.findall(r"^## (.*) \{#([a-z0-9-]+)\}$",body,re.M)
c("section ids/headings match",[(h,i) for h,i in heads]==[(s["heading"],s["id"]) for s in d["sections"]])
alltext=md+json.dumps(p,ensure_ascii=False)
c("no em/en dash","—" not in alltext and "–" not in alltext)
c("no bracket markers",not re.search(r"\[(VERIFY|OWNER CONFIRM|DATA NEEDED|LINK NEEDED)",body+json.dumps(p,ensure_ascii=False)))
vis=json.dumps(p,ensure_ascii=False).lower()
ti=re.findall(r"\b(ти|теб|тебе|твой|твоя|твоят|твоите|твоето|губиш|попълваш|получаваш|открий|запази)\b",vis)
c("no ти forms",not ti,ti)
lower=re.findall(r"(?<![.!?„\"]\s)(?<!^)\b(вие|ви|вас|ваш|вашия|вашата|вашите|вашият)\b",json.dumps(p,ensure_ascii=False))
c("no lowercase formal pronouns",not lower,lower)
banned=r"гарантир|гаранци|първо място|топ позиции|лидер|най-добр|революцион|магия|магическ|невероят|уникал|безпрецедент|следващо ниво|без никакви усилия|напълно автоматично|мощен ai|10x|удвои|сертифицира|само днес|ограничени места|побързайте|промоци|отстъпк|ваучер|отзив|доволни клиенти|доклад|seo копирайтинг|копирайтинг услуги"
c("no banned/hype/sibling terms",not re.findall(banned,vis),re.findall(banned,vis))
fr=re.findall(r"безплатн\w*\s+\w+",vis); c("безплатн only diagnosis",all("диагност" in x for x in fr),fr)
nums=re.findall(r"\d+",re.sub(r"\{\{\w+\}\}","",json.dumps({k:p[k] for k in ("lead","sections","faq","h1","summary","meta")},ensure_ascii=False)))
c("numbers only 30",set(nums)<={"30"},nums)
c("no periods",not re.search(r"часа|седмиц|за дни|дни|месец",vis.replace("месечен","")),re.findall(r"часа|седмиц|дни",vis))
links=re.findall(r"\]\(([^)]+)\)",json.dumps(p,ensure_ascii=False))
allowed=set(re.findall(r"^\| (/[^ ]*) \|",open("../../conversion-links.md",encoding="utf-8").read(),re.M))
c("links in conversion-links",all(l=="{{BOOKING_URL}}" or l in allowed for l in links),links)
c("one booking CTA",links.count("{{BOOKING_URL}}")==1)
c("related 3 valid",len(p["related"])==3 and all(r in allowed and r not in ("/",p["path"]) for r in p["related"]))
c("no service key","service" not in p)
c("H2 count 6-8",6<=len(p["sections"])<=8,len(p["sections"]))
c("FAQ 4-6",4<=len(p["faq"])<=6,len(p["faq"]))
def strs(s): return s["paragraphs"]+s.get("steps",[])+s.get("bullets",[])+s.get("closing",[])
wc=sum(len(re.sub(r"\]\([^)]*\)","]",x).split()) for s in p["sections"] for x in strs(s))
c("body words 900-1400",900<=wc<=1400,wc)
# strings identical md vs json
mdflat=re.sub(r"\s+"," ",body)
missing=[x for s in p["sections"] for x in strs(s) if x not in mdflat]
c("port strings == md strings",not missing and all(f["question"] in [x["q"] for x in d["faq"]] for f in p["faq"]),missing[:2])
c("example label present","пример, не реален случай" in vis)
for k in ["инструмент за съдържание","бранш и град","цели колекции","по график","преди да го одобрите","30-минутен разговор","оферта с приоритизирани решения и ясни еднократни цени","без дългосрочен договор","не ви задължава","срокът зависи от решението и го посочваме в офертата","/seo-statii/","/diagnostika/"]:
    c("inventory: "+k,k in vis)
for r in R: print("|",r[0],"|",r[1],"|",r[2],"|")
